-- Explicit opt-in migration. Never run automatically at application startup.
CREATE TABLE service_reports (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 external_id VARCHAR(80) NOT NULL UNIQUE,
 report_number VARCHAR(80) NULL UNIQUE,
 customer_external_id VARCHAR(80) NOT NULL,
 premise_id VARCHAR(100) NULL,
 job_external_id VARCHAR(80) NULL,
 contract_reference VARCHAR(120) NULL,
 contract_source VARCHAR(20) NULL,
 schedule_reference VARCHAR(255) NULL,
 customer_name VARCHAR(255) NOT NULL,
 site_name VARCHAR(255) NULL,
 service_type VARCHAR(255) NULL,
 company_type VARCHAR(12) NOT NULL,
 service_date DATE NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'Draft',
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 created_by VARCHAR(120) NOT NULL,
 prepared_by VARCHAR(255) NOT NULL,
 last_edited_by VARCHAR(120) NOT NULL,
 submitted_by VARCHAR(120) NULL,
 contributors JSON NOT NULL,
 assignees JSON NOT NULL,
 content JSON NOT NULL,
 has_findings TINYINT(1) NOT NULL DEFAULT 0,
 followup_required TINYINT(1) NOT NULL DEFAULT 0,
 followup_date DATE NULL,
 approved_version_id BIGINT UNSIGNED NULL,
 created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 KEY idx_sr_customer (customer_external_id, service_date),
 KEY idx_sr_status (status, service_date),
 KEY idx_sr_owner (created_by, service_date),
 KEY idx_sr_job (job_external_id),
 KEY idx_sr_followup (followup_required, followup_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE service_report_versions (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 report_id BIGINT UNSIGNED NOT NULL,
 revision INT UNSIGNED NOT NULL,
 state VARCHAR(30) NOT NULL,
 snapshot JSON NOT NULL,
 content_hash CHAR(64) NOT NULL,
 pdf_storage_key VARCHAR(120) NULL,
 pdf_sha256 CHAR(64) NULL,
 created_by VARCHAR(120) NOT NULL,
 created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE KEY uk_srv_revision (report_id, revision),
 FOREIGN KEY (report_id) REFERENCES service_reports(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE service_report_files (
 id CHAR(36) NOT NULL PRIMARY KEY,
 report_id BIGINT UNSIGNED NOT NULL,
 kind VARCHAR(20) NOT NULL,
 category VARCHAR(80) NOT NULL,
 caption TEXT NULL,
 area VARCHAR(255) NULL,
 annotations TEXT NULL,
 captured_at VARCHAR(40) NULL,
 display_order INT NOT NULL DEFAULT 0,
 include_in_pdf TINYINT(1) NOT NULL DEFAULT 1,
 original_name VARCHAR(255) NOT NULL,
 storage_key VARCHAR(120) NOT NULL UNIQUE,
 preview_storage_key VARCHAR(120) NULL,
 preview_sha256 CHAR(64) NULL,
 preview_byte_size BIGINT UNSIGNED NULL,
 mime_type VARCHAR(80) NOT NULL,
 byte_size BIGINT UNSIGNED NOT NULL,
 sha256 CHAR(64) NOT NULL,
 signed_content_hash CHAR(64) NULL,
 uploaded_by VARCHAR(120) NOT NULL,
 created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 removed_at TIMESTAMP(3) NULL,
 FOREIGN KEY (report_id) REFERENCES service_reports(id) ON DELETE RESTRICT,
 KEY idx_srf_report (report_id, removed_at, display_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE service_report_audit_logs (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 report_id BIGINT UNSIGNED NOT NULL,
 actor_id VARCHAR(120) NOT NULL,
 actor_name VARCHAR(255) NOT NULL,
 action VARCHAR(40) NOT NULL,
 revision INT UNSIGNED NOT NULL,
 details JSON NOT NULL,
 created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 FOREIGN KEY (report_id) REFERENCES service_reports(id) ON DELETE RESTRICT,
 KEY idx_sra_report (report_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE service_report_request_keys (
 actor_id VARCHAR(120) NOT NULL,
 request_key VARCHAR(100) NOT NULL,
 request_hash CHAR(64) NOT NULL,
 report_external_id VARCHAR(80) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (actor_id, request_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE service_report_permissions (
 employee_id VARCHAR(120) NOT NULL PRIMARY KEY,
 capabilities JSON NOT NULL,
 access_scope VARCHAR(12) NOT NULL DEFAULT 'assigned',
 updated_by VARCHAR(120) NOT NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
